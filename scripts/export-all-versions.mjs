#!/usr/bin/env node

/**
 * Export All 208 Git Commit Versions
 * Creates an exact codebase snapshot for every commit in the repository history,
 * accompanied by detailed commit metadata and a master chronological index.
 */

import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

const ROOT_DIR = process.cwd();
const OUTPUT_DIR = path.join(ROOT_DIR, 'history_versions');
const TEMP_DIR = path.join(ROOT_DIR, 'scratch', 'export_temp');

console.log('🚀 Initializing 208-Version Git Export Engine...');
console.log(`📁 Target Directory: ${OUTPUT_DIR}`);

// Ensure directories exist
fs.mkdirSync(OUTPUT_DIR, { recursive: true });
fs.mkdirSync(TEMP_DIR, { recursive: true });

// 1. Retrieve all commits in chronological order (oldest -> newest)
const logOutput = execSync('git log --reverse --format="%H|%h|%ad|%an|%s" --date=short', {
  cwd: ROOT_DIR,
  encoding: 'utf-8',
  maxBuffer: 10 * 1024 * 1024
});

const commits = logOutput
  .trim()
  .split('\n')
  .map(line => {
    const parts = line.split('|');
    return {
      fullHash: parts[0],
      shortHash: parts[1],
      date: parts[2],
      author: parts[3],
      subject: parts.slice(4).join('|')
    };
  })
  .filter(c => c.fullHash && c.shortHash);

const totalCommits = commits.length;
console.log(`📊 Discovered ${totalCommits} total commits in repository history.`);

const masterIndex = [];
const startTime = Date.now();

// 2. Export each commit
for (let i = 0; i < totalCommits; i++) {
  const commit = commits[i];
  const versionNum = String(i + 1).padStart(3, '0');
  
  // Clean subject for Windows folder name
  const cleanSubject = commit.subject
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 45) || 'commit';

  const folderName = `v${versionNum}_${commit.date}_${commit.shortHash}_${cleanSubject}`;
  const folderPath = path.join(OUTPUT_DIR, folderName);
  const tempZipPath = path.join(TEMP_DIR, `commit_${commit.shortHash}.zip`);

  fs.mkdirSync(folderPath, { recursive: true });

  try {
    // Export commit archive
    execSync(`git archive --format=zip ${commit.fullHash} -o "${tempZipPath}"`, {
      cwd: ROOT_DIR,
      stdio: 'pipe'
    });

    // Unpack archive into version folder
    execSync(`tar -xf "${tempZipPath}" -C "${folderPath}"`, {
      cwd: ROOT_DIR,
      stdio: 'pipe'
    });

    // Clean up zip
    if (fs.existsSync(tempZipPath)) {
      fs.unlinkSync(tempZipPath);
    }

    // Get commit details and file diff stats
    const commitDetails = execSync(`git show --stat --no-color ${commit.fullHash}`, {
      cwd: ROOT_DIR,
      encoding: 'utf-8',
      maxBuffer: 5 * 1024 * 1024
    });

    // Create per-commit metadata card
    const metaCard = `# Version ${versionNum} / ${totalCommits} — Commit Snapshot

## 📌 Commit Details
- **Version Number**: \`${versionNum}\` of \`${totalCommits}\`
- **Commit Date**: \`${commit.date}\`
- **Short Hash**: \`${commit.shortHash}\`
- **Full Hash**: \`${commit.fullHash}\`
- **Author**: \`${commit.author}\`
- **Subject**: **${commit.subject}**

---

## 📈 Git Show & File Stat Summary
\`\`\`text
${commitDetails.trim()}
\`\`\`

---
*Generated by Sheet-Bot Version Archive Engine on ${new Date().toISOString()}*
`;

    fs.writeFileSync(path.join(folderPath, 'COMMIT_DETAILS.md'), metaCard, 'utf-8');

    masterIndex.push({
      version: versionNum,
      date: commit.date,
      shortHash: commit.shortHash,
      fullHash: commit.fullHash,
      author: commit.author,
      subject: commit.subject,
      folder: folderName
    });

    if ((i + 1) % 25 === 0 || i + 1 === totalCommits) {
      const elapsed = ((Date.now() - startTime) / 1000).toFixed(1);
      console.log(`⏳ Progress: ${i + 1}/${totalCommits} commits exported (${elapsed}s)...`);
    }
  } catch (err) {
    console.error(`❌ Error exporting commit ${commit.shortHash}:`, err.message);
  }
}

// 3. Generate MASTER_VERSIONS_INDEX.md
console.log('📝 Generating Master Versions Index and README...');

let masterContent = `# 📚 Master Repository Evolution & Version Archive

Total Versions Archived: **${totalCommits}**  
Date Range: **${commits[0]?.date}** to **${commits[totalCommits - 1]?.date}**  
Generated: **${new Date().toISOString()}**

This directory contains standalone codebase snapshots of every single commit in the project's history. Each folder contains the exact source tree at that revision along with a \`COMMIT_DETAILS.md\` file detailing changes, author, and statistics.

---

## 📋 Chronological Commit Catalog

| Version | Date | Short Hash | Folder Link | Commit Message | Author |
| :---: | :---: | :---: | :--- | :--- | :--- |
`;

for (const item of masterIndex) {
  const safeSubject = item.subject.replace(/\|/g, '\\|');
  masterContent += `| **${item.version}** | \`${item.date}\` | \`${item.shortHash}\` | [\`${item.folder}\`](./${item.folder}/) | ${safeSubject} | \`${item.author}\` |\n`;
}

fs.writeFileSync(path.join(OUTPUT_DIR, 'MASTER_VERSIONS_INDEX.md'), masterContent, 'utf-8');
fs.writeFileSync(path.join(OUTPUT_DIR, 'README.md'), masterContent, 'utf-8');

// Clean up temp dir
try {
  fs.rmSync(TEMP_DIR, { recursive: true, force: true });
} catch (_) {}

const totalElapsed = ((Date.now() - startTime) / 1000).toFixed(1);
console.log(`\n🎉 Successfully exported all ${totalCommits} versions to:`);
console.log(`📂 ${OUTPUT_DIR}`);
console.log(`⏱️ Total Time: ${totalElapsed} seconds.`);
